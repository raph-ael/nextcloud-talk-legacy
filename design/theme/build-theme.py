#!/usr/bin/env python3
"""Builds the accent colours of every platform from one source: design/theme/accents.json.

    python3 design/theme/build-theme.py

Checks the contrast first and stops on a colour that is too weak:
  - own bubble and light accent with white text: at least 4.5:1
  - dark accent: at least 4.0:1 with white text (buttons) and on the dark background
    #121212 (links, icons), so it works both ways

Then writes (checked in, like the icons; running it again gives identical files):
  desktop/src/renderer/src/accents.ts
  android/app/src/main/java/org/wolkenfunk/app/ui/Accents.kt
  ios/TalkApp/UI/Accents.swift
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "theme" / "accents.json"
WHITE = "#FFFFFF"
DARK_BG = "#121212"

OUT_TS = ROOT / "desktop/src/renderer/src/accents.ts"
OUT_KT = ROOT / "android/app/src/main/java/org/wolkenfunk/app/ui/Accents.kt"
OUT_SWIFT = ROOT / "ios/TalkApp/UI/Accents.swift"

HEADER = "Generated by design/theme/build-theme.py from design/theme/accents.json. Do not edit."


def rgb(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    if len(h) != 6:
        raise ValueError(f"not #RRGGBB: {h}")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def hexc(c: tuple[float, float, float]) -> str:
    return "#%02X%02X%02X" % tuple(max(0, min(255, round(x))) for x in c)


def luminance(h: str) -> float:
    def ch(v: int) -> float:
        x = v / 255
        return x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4

    r, g, b = (ch(v) for v in rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def mix(h: str, other: str, amount: float) -> str:
    a, b = rgb(h), rgb(other)
    return hexc(tuple(x + (y - x) * amount for x, y in zip(a, b)))


def load() -> tuple[str, list[dict]]:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    accents = []
    for a in data["accents"]:
        light, dark = a["light"].upper(), a["dark"].upper()
        accents.append(
            {
                "id": a["id"],
                "name": a["name"],
                "light": light,
                "dark": dark,
                "hover_light": a.get("hoverLight", mix(light, "#000000", 0.12)).upper(),
                "hover_dark": a.get("hoverDark", mix(dark, "#FFFFFF", 0.12)).upper(),
                "bubble": a.get("bubble", light).upper(),
            }
        )
    ids = [a["id"] for a in accents]
    if len(set(ids)) != len(ids) or data["default"] not in ids:
        sys.exit("accents.json: ids must be unique and contain the default")
    return data["default"], accents


def check(accents: list[dict]) -> None:
    errors = []
    for a in accents:
        rules = [
            ("light accent / white text", contrast(a["light"], WHITE), 4.5),
            ("own bubble / white text", contrast(a["bubble"], WHITE), 4.5),
            ("light hover / white text", contrast(a["hover_light"], WHITE), 4.5),
            ("dark accent / white text", contrast(a["dark"], WHITE), 4.0),
            ("dark accent / dark background", contrast(a["dark"], DARK_BG), 4.0),
            ("dark hover / dark background", contrast(a["hover_dark"], DARK_BG), 4.0),
        ]
        for what, got, need in rules:
            if got < need:
                errors.append(f"{a['id']}: {what} {got:.2f} < {need}")
    if errors:
        sys.exit("contrast too weak:\n  " + "\n  ".join(errors))


def ts(default: str, accents: list[dict]) -> str:
    rows = "\n".join(
        f"  {{ id: '{a['id']}', name: '{a['name']}', "
        f"light: {{ accent: '{a['light']}', hover: '{a['hover_light']}', bubble: '{a['bubble']}' }}, "
        f"dark: {{ accent: '{a['dark']}', hover: '{a['hover_dark']}', bubble: '{a['bubble']}' }} }},"
        for a in accents
    )
    return f"""// {HEADER}
// Accent colours (docs/settings.md „Darstellung“).

export interface AccentColors {{
  accent: string
  hover: string
  /** Own message bubble (white text). */
  bubble: string
}}

export interface Accent {{
  id: string
  /** German name, also the label of the swatch. */
  name: string
  light: AccentColors
  dark: AccentColors
}}

export const DEFAULT_ACCENT = '{default}'

export const ACCENTS: readonly Accent[] = [
{rows}
]

export function accentById(id: string | null | undefined): Accent {{
  return ACCENTS.find((a) => a.id === id) ?? ACCENTS.find((a) => a.id === DEFAULT_ACCENT)!
}}
"""


def argb(h: str) -> str:
    return "0xFF" + h.lstrip("#")


def kt(default: str, accents: list[dict]) -> str:
    rows = "\n".join(
        f'    Accent("{a["id"]}", "{a["name"]}", '
        f'AccentColors(Color({argb(a["light"])}), Color({argb(a["hover_light"])}), Color({argb(a["bubble"])})), '
        f'AccentColors(Color({argb(a["dark"])}), Color({argb(a["hover_dark"])}), Color({argb(a["bubble"])}))),'
        for a in accents
    )
    return f"""// {HEADER}
// Accent colours (docs/settings.md „Darstellung“).
package org.wolkenfunk.app.ui

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

@Immutable
data class AccentColors(
    val accent: Color,
    val hover: Color,
    /** Own message bubble (white text). */
    val bubble: Color,
)

@Immutable
data class Accent(
    val id: String,
    /** German name, also the label of the swatch. */
    val name: String,
    val light: AccentColors,
    val dark: AccentColors,
)

const val DEFAULT_ACCENT = "{default}"

val ACCENTS: List<Accent> = listOf(
{rows}
)

fun accentById(id: String?): Accent =
    ACCENTS.firstOrNull {{ it.id == id }} ?: ACCENTS.first {{ it.id == DEFAULT_ACCENT }}
"""


def swift_hex(h: str) -> str:
    return "0x" + h.lstrip("#")


def swift(default: str, accents: list[dict]) -> str:
    rows = "\n".join(
        f'        Accent(id: "{a["id"]}", name: "{a["name"]}", '
        f'light: .init(accent: {swift_hex(a["light"])}, hover: {swift_hex(a["hover_light"])}, bubble: {swift_hex(a["bubble"])}), '
        f'dark: .init(accent: {swift_hex(a["dark"])}, hover: {swift_hex(a["hover_dark"])}, bubble: {swift_hex(a["bubble"])})),'
        for a in accents
    )
    return f"""// {HEADER}
// Accent colours (docs/settings.md „Darstellung“).

struct AccentColors: Equatable {{
    let accent: UInt32
    let hover: UInt32
    /// Own message bubble (white text).
    let bubble: UInt32
}}

struct Accent: Identifiable, Equatable {{
    let id: String
    /// German name, also the label of the swatch.
    let name: String
    let light: AccentColors
    let dark: AccentColors

    static let defaultID = "{default}"

    static let all: [Accent] = [
{rows}
    ]

    static func byID(_ id: String?) -> Accent {{
        all.first {{ $0.id == id }} ?? all.first {{ $0.id == defaultID }}!
    }}
}}
"""


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    default, accents = load()
    check(accents)
    for a in accents:
        print(
            f"{a['id']:10} light {contrast(a['light'], WHITE):.2f}  bubble {contrast(a['bubble'], WHITE):.2f}  "
            f"dark {contrast(a['dark'], WHITE):.2f}/{contrast(a['dark'], DARK_BG):.2f}"
        )
    write(OUT_TS, ts(default, accents))
    write(OUT_KT, kt(default, accents))
    write(OUT_SWIFT, swift(default, accents))


if __name__ == "__main__":
    main()
