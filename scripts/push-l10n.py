#!/usr/bin/env python3
"""Writes core/talk-core/src/push_l10n.rs from the translations of Nextcloud Talk.

The push for a reaction says "{user} reacted with {reaction}" in the language of the
user's account, nothing else marks it. The core recognises it by these sentences.

    git clone --depth 1 --branch <tag> --filter=blob:none --sparse \
        https://github.com/nextcloud/spreed.git /tmp/spreed
    git -C /tmp/spreed sparse-checkout set l10n
    scripts/push-l10n.py /tmp/spreed <tag> > core/talk-core/src/push_l10n.rs
"""
import glob
import json
import os
import re
import sys

IN_CALL = "{user} in {call}"
REACTED = [
    "{user} reacted with {reaction}",
    "{user} reacted with {reaction} in {call}",
    "{guest} (guest) reacted with {reaction} in {call}",
    "Guest reacted with {reaction} in {call}",
    "Deleted user reacted with {reaction} in {call}",
]


def rust(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    checkout, tag = sys.argv[1], sys.argv[2]
    # English is the source and stands for every language without a translation.
    rows = [("en", IN_CALL, list(REACTED))]
    seen = set(REACTED)
    for path in sorted(glob.glob(os.path.join(checkout, "l10n", "*.json"))):
        with open(path, encoding="utf-8") as f:
            t = json.load(f)["translations"]

        def tr(key):
            value = t.get(key)
            return value.strip() if isinstance(value, str) and value.strip() else key

        new = []
        for key in REACTED:
            sentence = tr(key)
            if sentence not in seen and "{reaction}" in sentence:
                seen.add(sentence)
                new.append(sentence)
        if new:
            rows.append((os.path.basename(path)[:-5], tr(IN_CALL), new))

    # The sentence with the most words of its own first, across all languages: "Guest
    # reacted with …" is also "{user} reacted with …" for someone called Guest.
    flat = [(sentence, in_call, lang) for lang, in_call, sentences in rows for sentence in sentences]
    flat.sort(key=lambda row: -len(re.sub(r"\{\w+\}", "", row[0])))
    out = [
        f"// Generated by scripts/push-l10n.py from Nextcloud Talk {tag} (l10n/*.json). Do not edit.",
        "",
        "/// The first lines of a reaction push in the server's languages, the most specific",
        "/// first, each with how that language names the sender of a group push",
        "/// (`{user} in {call}`). A sentence several languages share is listed once.",
        "pub(crate) const REACTIONS: &[(&str, &str)] = &[",
    ]
    out.extend(f"    ({rust(sentence)}, {rust(in_call)}), // {lang}" for sentence, in_call, lang in flat)
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
